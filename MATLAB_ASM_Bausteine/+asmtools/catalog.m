function K = catalog()
%CATALOG Block catalogue of the ASM library (single source for ports, masks and help texts).
%   K = asmtools.catalog() returns a struct array with one element per block.
%   build_library.m builds the library from it, the tests check the library against it.
%
%   Fields per block
%     id           code identifier (ASCII)
%     name         block name in the library (shown to the user, German)
%     category     sources | machine | mechanics | sensors | didactics | reference
%     kind         physical   mask over a Simscape component (ssc)
%                  compact    mask over the decomposed motor (several components)
%                  fl         mask over a block of the Simscape Foundation Library
%                  ee         mask over the ee_lib induction machine (reference)
%                  simulink   mask over a Simulink subsystem
%     ssc          component path (kind = physical) or library path (kind = fl)
%     ports        physical connections: name, domain (el | mech | ls), side (left | right)
%     inputs, outputs   Simulink inputs/outputs: name, width, unit
%     par          mask parameters: name, prompt, unit, value, type, options, rule
%     description, equations, source   texts for mask description and help (German)
%     symbol       icon code (asmtools.icon)
%     raw, derived signal routing of physical blocks (see end of this file)
%     status       'implemented' | 'placeholder'
%
%   Rules for value ranges (field rule, separated by ';'):
%     pos       value > 0             min=x / max=x   bounds inclusive
%     int       integer               vector          row or column vector allowed
%   Empty rule: finite real scalar.
%
%   All default values are example values (see parameter/asm_standard.m).

S  = asm_standard();
Q  = 'Hagl, R.: Elektrische Antriebstechnik. Hanser, München 2013';
QA = [Q '; Densborn, Skript "DS-Asynchron-Motor" (DHBW Mannheim)'];
QD = [Q '; Densborn, Skript "Drehstrom & Drehfeld" (DHBW Mannheim)'];
