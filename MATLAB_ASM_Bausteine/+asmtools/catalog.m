function b = blk(id, name, category, kind, ssc, ports, inputs, outputs, par, description, equations, source, symbol)
b = struct('id', id, 'name', name, 'category', category, 'kind', kind, 'ssc', ssc, ...
    'ports', or_empty(ports, pt('', '', '')), 'inputs', or_empty(inputs, sg('', 0, '')), ...
    'outputs', or_empty(outputs, sg('', 0, '')), 'par', or_empty(par, pe('', '', '', '', '')), ...
    'description', description, 'equations', equations, 'source', source, 'symbol', symbol);
end

function x = or_empty(x, template)
% empty input as 0x0 struct with the correct fields
if isempty(x), x = template([]); end
end

