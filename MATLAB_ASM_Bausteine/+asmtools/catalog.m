    'Raumzeigermodell, statorfest (Index 1 = Stator, 2 = Rotor, ′ = statorbezogen):', ...
    '  u1 = R1·i1 + dψ1/dt', ...
    '  0  = R2′·i2′ + dψ2′/dt − j·p·Ω·ψ2′', ...
    '  ψ1 = L1σ·i1 + ψh,   ψ2′ = L2σ′·i2′ + ψh,   ψh = Lh·(i1 + i2′)', ...
    '  M  = 3/2·p·Im{ψh*·i1},   J·dΩ/dt = M − M_L − k_R·Ω', ...
    '  n = 60·Ω/(2π),   s = (ns − n)/ns,   ns = 60·f1/p');
