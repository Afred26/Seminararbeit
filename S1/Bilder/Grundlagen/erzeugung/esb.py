# T-Ersatzschaltbild eines Strangs der Asynchronmaschine (stationär, Rotorgrößen statorbezogen)
# Schaltzeichen nach DIN EN 60617: Widerstand = leeres Rechteck, Induktivität = gefülltes Rechteck
import schemdraw, schemdraw.elements as elm
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
plt.rcParams.update({"font.family":"Liberation Sans","mathtext.fontset":"dejavusans"})
schemdraw.config(fontsize=19, lw=1.3, font="Liberation Sans")
H = 3.6
R = lambda: elm.ResistorIEC()
L = lambda: elm.ResistorIEC().fill("black")
with schemdraw.Drawing(show=False) as d:
    d.config(unit=2.4)
    d += (a := elm.Dot(open=True))
    d += elm.Line().right(0.9)
    d += R().right().label(r"$R_1$", ofst=0.15)
    d += elm.Line().right(0.5)
    d += L().right().label(r"$\mathrm{j}X_{1\sigma}$", ofst=0.15)
    d += elm.Line().right(0.7)
    d += (k := elm.Dot())
    d += elm.Line().right(0.7)
    d += L().right().label(r"$\mathrm{j}X'_{2\sigma}$", ofst=0.15)
    d += elm.Line().right(0.5)
    d += R().right().label(r"$R'_2$", ofst=0.15)
    d += elm.Line().right(0.9)
    d += (rl := R().down(H))
    d += elm.Line().left().tox(k.end)
    d += elm.Dot()
    d += elm.Line().left().tox(a.start)
    d += (b := elm.Dot(open=True))
    d += L().at(k.end).down(H)
    xk, xr, x0 = k.end[0], rl.start[0], a.start[0]
    # Beschriftungen
    d += elm.Label().at((xk+0.45, -H/2)).label(r"$\mathrm{j}X_\mathrm{h}$", halign="left")
    d += elm.Label().at((xr+0.45, -H/2)).label(r"$R'_2\,\dfrac{1-s}{s}$", halign="left")
    # Zählpfeile (Verbraucherzählpfeilsystem)
    d += elm.Arrow().at((x0-0.55, -0.35)).down(H-0.7).color("#0072BD")
    d += elm.Label().at((x0-0.8, -H/2)).label(r"$\underline{U}_1$", halign="right", color="#0072BD")
    d += elm.Arrow().at((x0+0.15, 0.5)).right(0.9).color("#D95319")
    d += elm.Label().at((x0+0.6, 0.95)).label(r"$\underline{I}_1$", color="#D95319")
    d += elm.Arrow().at((xr-0.15, 0.5)).left(0.9).color("#D95319")
    d += elm.Label().at((xr-0.6, 0.95)).label(r"$\underline{I}'_2$", color="#D95319")
    d += elm.Arrow().at((xk-0.5, -0.45)).down(0.9).color("#D95319")
    d += elm.Label().at((xk-0.8, -0.95)).label(r"$\underline{I}_\mu$", halign="right", color="#D95319")
    d.save("/home/claude/build/fig/asm_esb.svg"); d.save("/home/claude/build/fig/asm_esb.png", dpi=220)
